DROP TABLE IF EXISTS ListaGledanja;
DROP TABLE IF EXISTS Ocena;
DROP TABLE IF EXISTS FilmTag;
DROP TABLE IF EXISTS Tag;
DROP TABLE IF EXISTS Pripada;
DROP TABLE IF EXISTS Zanr;
DROP TABLE IF EXISTS Film;
DROP TABLE IF EXISTS Korisnik;
GO

CREATE TABLE Korisnik (
    idKorisnik INT PRIMARY KEY IDENTITY(1,1),
    korisnickoIme NVARCHAR(100) NOT NULL,
    brojNagrada INT NOT NULL DEFAULT 0,
    opis NVARCHAR(100) NOT NULL DEFAULT 'undefined'
);

CREATE TABLE Zanr (
    idZanr INT PRIMARY KEY IDENTITY(1,1),
    naziv NVARCHAR(100) NOT NULL
);

CREATE TABLE Tag (
    idTag INT PRIMARY KEY IDENTITY(1,1),
    naziv NVARCHAR(100) NOT NULL
);

CREATE TABLE Film (
    idFilm INT PRIMARY KEY IDENTITY(1,1),
    naslov NVARCHAR(100) NOT NULL,
    reziser NVARCHAR(100) NOT NULL,
    status NVARCHAR(100) NULL, -- Može biti NULL dok nema ocena i trenda
    prosecnaOcena DECIMAL(10,3) NOT NULL DEFAULT 0.000
);

CREATE TABLE ListaGledanja (
    idListaGledanja INT PRIMARY KEY IDENTITY(1,1),
    idFilm INT NOT NULL,
    idKorisnik INT NOT NULL,
    status NVARCHAR(100) NOT NULL,
    CONSTRAINT FK_ListaGledanja_Film FOREIGN KEY (idFilm) REFERENCES Film(idFilm) ON UPDATE CASCADE ON DELETE NO ACTION,
    CONSTRAINT FK_ListaGledanja_Korisnik FOREIGN KEY (idKorisnik) REFERENCES Korisnik(idKorisnik) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE Ocena (
    idOcena INT PRIMARY KEY IDENTITY(1,1),
    ocena INT NOT NULL,
    idKorisnik INT NOT NULL,
    idFilm INT NOT NULL,
    vreme DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_Ocena_Korisnik FOREIGN KEY (idKorisnik) REFERENCES Korisnik(idKorisnik) ON UPDATE CASCADE ON DELETE NO ACTION,
    CONSTRAINT FK_Ocena_Film FOREIGN KEY (idFilm) REFERENCES Film(idFilm) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE Pripada (
    idPripada INT PRIMARY KEY IDENTITY(1,1),
    idFilm INT NOT NULL,
    idZanr INT NOT NULL,
    CONSTRAINT FK_Pripada_Film FOREIGN KEY (idFilm) REFERENCES Film(idFilm) ON UPDATE CASCADE ON DELETE NO ACTION,
    CONSTRAINT FK_Pripada_Zanr FOREIGN KEY (idZanr) REFERENCES Zanr(idZanr) ON UPDATE CASCADE ON DELETE NO ACTION
);

CREATE TABLE FilmTag (
    idFilmTag INT PRIMARY KEY IDENTITY(1,1),
    idFilm INT NOT NULL,
    idTag INT NOT NULL,
    CONSTRAINT FK_FilmTag_Film FOREIGN KEY (idFilm) REFERENCES Film(idFilm) ON UPDATE CASCADE ON DELETE NO ACTION,
    CONSTRAINT FK_FilmTag_Tag FOREIGN KEY (idTag) REFERENCES Tag(idTag) ON UPDATE CASCADE ON DELETE NO ACTION
);
GO